def _normalize(text: str) -> str:
    return " ".join((text or "").replace(":", "").split()).strip()


def _lookup_help(
    text: str,
    context_name: str | None = None,
) -> str | None:
    key = _normalize(text)

    if not key:
        return None

    if context_name:
        contextual = CONTEXT_HELP_TEXTS.get(context_name, {})
        if key in contextual:
            return contextual[key]

    if key in HELP_TEXTS:
        return HELP_TEXTS[key]

    # Allow labels that include values after a known caption.
    for caption, help_text in HELP_TEXTS.items():
        normalized_caption = _normalize(caption)
        if key.startswith(normalized_caption + " "):
            return help_text

    return None


def _tooltip_html(help_text: str) -> str:
    escaped = html.escape(help_text)
    return (
        '<div style="width: 320px; max-width: 320px; '
        'white-space: normal; line-height: 1.35;">'
        f'{escaped}'
        '</div>'
    )


def _decorate_label(label: QLabel, help_text: str) -> None:
    if label.property("mastixaHelpApplied"):
        return

    label.setToolTip(_tooltip_html(help_text))
    label.setProperty("mastixaHelpApplied", True)

    original = label.text().strip()
    if original and "ⓘ" not in original:
        label.setText(f"{original}  ⓘ")


def _set_widget_help(widget: QWidget, help_text: str) -> None:
    if widget.toolTip():
        return
    widget.setToolTip(_tooltip_html(help_text))


def apply_help_tooltips(root: QWidget) -> None:
    """
    Adds explanatory help across the UI.

    Ambiguous captions such as "Κατάσταση" are resolved from the page class,
    so Declaration / Upload Center / Equipment do not show the same tooltip.
    """
    context_name = root.__class__.__name__

    for form in root.findChildren(QFormLayout):
        for row in range(form.rowCount()):
            label_item = form.itemAt(
                row,
                QFormLayout.ItemRole.LabelRole,
            )
            field_item = form.itemAt(
                row,
                QFormLayout.ItemRole.FieldRole,
            )

            if label_item is None:
                continue

            label_widget = label_item.widget()
            if not isinstance(label_widget, QLabel):
                continue

            help_text = _lookup_help(
                label_widget.text(),
                context_name,
            )
            if not help_text:
                continue

            _decorate_label(label_widget, help_text)

            if field_item is not None:
                field_widget = field_item.widget()
                if isinstance(field_widget, QWidget):
                    _set_widget_help(field_widget, help_text)

    for label in root.findChildren(QLabel):
        help_text = _lookup_help(
            label.text(),
            context_name,
        )
        if help_text:
            _decorate_label(label, help_text)

    for group in root.findChildren(QGroupBox):
        help_text = _lookup_help(
            group.title(),
            context_name,
        )
        if help_text:
            group.setToolTip(_tooltip_html(help_text))
